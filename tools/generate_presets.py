"""Embed the shared preset directory for C and Python; no runtime file lookup."""
import json
from pathlib import Path


def generate(source, destination):
    source, destination = Path(source), Path(destination)
    packs = []
    namespaces = set()
    lines = ['/* Generated by tools/generate_presets.py; edit presets/*.json. */',
             'typedef struct { const char *name; const unsigned char *data; size_t size; } EmbeddedPreset;']
    paths = [source / 'defaults.json'] + sorted(p for p in source.glob('*.json') if p.name != 'defaults.json')
    for i, path in enumerate(paths):
        obj = json.loads(path.read_text(encoding='utf-8'))
        data = json.dumps(obj, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
        if i:
            namespace = obj['namespace'].upper()
            if namespace in namespaces:
                raise ValueError(f'Duplicate preset namespace: {namespace}')
            namespaces.add(namespace)
            names = set()
            for name, target in obj['document_types'].items():
                if name.upper() in names or target not in obj['rule_sets']:
                    raise ValueError(f'Invalid or duplicate document type in {path}: {name}')
                names.add(name.upper())
            packs.append((namespace, i, len(data)))
        lines.append(f'static const unsigned char preset_bytes_{i}[] = {{')
        lines.extend(','.join(str(b) for b in data[j:j+32]) + ',' for j in range(0, len(data), 32))
        lines.append('0};')
    lines.append('static const EmbeddedPreset embedded_presets[] = {')
    lines.extend(f'{{{json.dumps(name)},preset_bytes_{i},{size}}},' for name, i, size in packs)
    lines.append('};\n')
    text = '\n'.join(lines)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_text(encoding='ascii') != text:
        destination.write_text(text, encoding='ascii', newline='\n')


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    generate(root / 'presets', root / 'c/src/preset_data.h')
